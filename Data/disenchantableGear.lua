--- True only for known green or blue disenchantable gear; unknown/custom items stay unchanged.
function addon:IsFilteredGear(item)
	local kind = type(item)
	local id = kind == "number" and item or kind == "string" and (tonumber(item) or tonumber(item:match("item:(%d+)")))
	if not id or not eligible[id] then return false end
	local quality = select(3, GetItemInfo(id))
	return quality == nil or quality == 2 or quality == 3 -- respect cached server quality overrides
end
